"""Write paper/aas/numbers.tex: every number quoted in ms.tex, from paper/results/*.json.

A missing result is written as a bold "??" so the PDF shows what is still to run.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "paper" / "results"
OUT = ROOT / "paper" / "aas" / "numbers.tex"


def _load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def k_str(ln_k):
    k = float(np.exp(ln_k))
    return f"{k:.2g}" if k < 10 else f"{k:.0f}"


def pct(x):
    return f"{100 * x:.1f}\\%" if x < 0.1 else f"{100 * x:.0f}\\%"


def main():
    m = {}
    main_ = _load("main")
    nd = _load("nondet")
    if main_:
        m["NbbSixteen"] = str(main_["bb16"]["n_obj"])
        m["KbbOrbits"] = k_str(main_["bb16"]["ln_bf"])
    if nd:
        m["KbbNondet"] = k_str(nd["bb16"]["ln_bf"])
    sm = _load("selmarg")
    if sm:
        m["KselMarg"] = k_str(sm["bma_discrete"]["ln_bf"])
        m["KselMargCont"] = k_str(sm["bma_continuous"]["ln_bf"])
    h = _load("history")
    if h:
        rows = h["bb16"]
        peak = max(rows, key=lambda r: r["ln_bf"])
        m["lnKpeak"] = f"{peak['ln_bf']:.1f}"
        m["YearPeak"] = str(int(peak["year"]))
        pre = [r for r in rows if r["year"] <= 2015][-1]
        m["KpreTwoThousandSixteen"] = k_str(pre["ln_bf"])
    pr = _load("predictive_2015")
    if pr:
        m["NtrainObjects"] = str(pr["n_train"])
        m["NnewObjects"] = str(pr["n_test"])
        m["lnKnew"] = f"{pr['ln_k_new_observed']:.2f}"
        m["KnewObjects"] = k_str(pr["ln_k_new_observed"])
        m["PnewUnderPlanet"] = pct(pr["p_value_under_trained_planet"])
        m["PnewUnderNull"] = pct(pr["frac_null_below_obs"])
    rows = []
    for p in sorted(RES.glob("predictive_*.json")):
        d = json.loads(p.read_text())
        sel = d.get("selection", {"radius_deg": 2.0, "a_min": 0.0})
        sel_s = "baseline" if sel["a_min"] == 0 else f"$a>{sel['a_min']:g}$\\,au footprint"
        rows.append(f"{d['split_year']} & {sel_s} & {d['n_train']} & {d['n_test']} & {d['ln_k_new_observed']:.2f} & "
                    f"{d['p_value_under_trained_planet']:.3f} & {d['frac_null_below_obs']:.2f} \\\\")
    m["PredictiveRows"] = "\n".join(rows) if rows else "??"
    f = _load("lsst_forecast")
    if f:
        m["NKhundredLSST"] = f"{f['lsst_implied']['N_K100']:.0f}--{f['lsst_implied']['N90_K100']:.0f}"
        m["NKhundredCurrent"] = f"{f['current_implied']['N_K100']:.0f}--{f['current_implied']['N90_K100']:.0f}"
    y = _load("lsst_yield")
    if y:
        b = y["variants"]["baseline"]["V24.5"]
        m["YieldLSST"] = f"{b['N_lsst']:.0f}"
        m["YieldLSSTrange"] = f"{b['N_lsst_16']:.0f}--{b['N_lsst_84']:.0f}"
        # Decision time: assume the ten-year yield accrues linearly after a two-opposition arc requirement.
        if f:
            n90 = f["lsst_implied"]["N90_K100"]
            yrs = [1.0 + 10.0 * n90 / n_tot for n_tot in (b["N_lsst_84"], b["N_lsst_16"])]
            m["YieldYears"] = f"{min(yrs):.0f}--{max(yrs):.0f} years"
            n50 = f["lsst_implied"]["N_K100"]
            yrs = [1.0 + 10.0 * n50 / n_tot for n_tot in (b["N_lsst_84"], b["N_lsst_16"])]
            m["YieldYearsMedian"] = f"{min(yrs):.0f}--{max(yrs):.0f} years"
    nb = _load("nbody_population")
    if nb:
        far = [np.mean([p["R_varpi"] for p in r["profile"] if p["a_lo"] >= 750]) for r in nb.values()]
        near = [np.mean([p["R_varpi"] for p in r["profile"] if p["a_hi"] <= 250]) for r in nb.values()]
        m["NbodyRfar"] = f"{min(far):.2f}--{max(far):.2f}"
        m["NbodyRnear"] = f"{max(near):.2f}"
        m["NbodySummary"] = (f"perihelion clustering with mean resultant length {min(far):.2f}--{max(far):.2f} beyond 750\\,au "
                             f"and below {max(near):.2f} inside 250\\,au")
    post = RES / "posterior_bb16_nondet.npy"
    if post.exists():
        from scipy.special import i0e, i1e
        th = np.median(np.load(post), axis=0)
        k = 10 ** th[7]  # log10_kvarpi
        m["DataR"] = f"{th[6] * i1e(k) / i0e(k):.2f}"
    names = ["NbbSixteen", "KbbOrbits", "KbbNondet", "KselMarg", "KselMargCont", "lnKpeak", "YearPeak",
             "KpreTwoThousandSixteen", "NtrainObjects", "NnewObjects", "lnKnew", "KnewObjects", "PnewUnderPlanet",
             "PnewUnderNull", "NKhundredLSST", "NKhundredCurrent", "YieldLSST", "YieldLSSTrange", "YieldYears", "YieldYearsMedian", "PredictiveRows",
             "NbodySummary", "NbodyRfar", "NbodyRnear", "DataR"]
    lines = ["% generated by scripts/make_numbers_tex.py -- do not edit"]
    for n in names:
        lines.append(f"\\newcommand{{\\{n}}}{{{m.get(n, '\\textbf{??}')}}}")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
